import {test} from 'node:test';
import assert from 'node:assert/strict';
import {researchProfileFor,DEEP_EVIDENCE_REVISION,RESEARCH_NEEDS_REVISION} from '../src/research-intent.mjs';
import {readResearchNeeds,researchNeedsTool,researchNeedsInstruction,RESEARCH_NEEDS_TOOL,RESEARCH_NEEDS_RECEIPT} from '../src/research-needs.mjs';
const profile=researchProfileFor('deep',RESEARCH_NEEDS_REVISION);
const auto=researchProfileFor('auto',RESEARCH_NEEDS_REVISION);
const prompt={role:'user',content:'This is the exact original user question.'};
const update=(id='first',status='open')=>({items:[{id,need:'Check an original',status}]});
const call=(id,args=update())=>({id,name:RESEARCH_NEEDS_TOOL,arguments:args});
const pair=(subject,value,opts={})=>[{role:'assistant',calls:[subject]},{role:'tool',callId:subject.id,result:{callId:subject.id,status:'succeeded',dispatched:true,value,...opts}}];
const intent={id:'intent',name:'select_research_intent',arguments:{intent:'deep'}};
const receipt=items=>({kind:RESEARCH_NEEDS_RECEIPT,items});
const fallback={kind:'original-question',items:[{id:'original-question',needRef:'current-user-request',status:'open'}]};
const malformed={items:[{...update().items[0],proof:true}]};
test('authoring and reopening require a valid originating Deep tool call, never prose or source copies',async()=>{
 let snapshot={messages:[prompt]};const tool=researchNeedsTool(profile,()=>snapshot);
 const first=call('first'),bad=call('bad',malformed),reopen=call('rev3',update('first','open')),closed=call('rev2',update('first','resolved'));
 assert.deepEqual(readResearchNeeds(profile,snapshot),fallback);
 assert.equal(readResearchNeeds(auto,snapshot),null);
 assert.equal(readResearchNeeds(researchProfileFor('deep',DEEP_EVIDENCE_REVISION),snapshot),null);
 assert.equal((await tool.execute(first.arguments,{callId:first.id})).reason,'unmatched');
 snapshot.messages.push({role:'assistant',calls:[first]});
 const accepted=await tool.execute(first.arguments,{callId:first.id});
 assert.deepEqual(accepted,receipt(first.arguments.items));
 assert.deepEqual(await tool.reconcile(first.arguments,{callId:first.id}),accepted);
 await tool.verifyResult(accepted,{call:first});
 await assert.rejects(tool.verifyResult(receipt([]),{call:first}),{code:'RESEARCH_NEEDS_RECEIPT_CHANGED'});
 snapshot.messages=[prompt,...pair(bad,{kind:'research-needs-unapplied@1',reason:'invalid_input'})];
 assert.deepEqual(await tool.execute(malformed,{callId:bad.id}),{kind:'research-needs-unapplied@1',reason:'invalid_input'});
 assert.deepEqual(readResearchNeeds(profile,snapshot),{...fallback,updateError:'invalid_input'});
 snapshot.messages.push(...pair({...first,name:'public_web_read'},accepted),{role:'assistant',content:JSON.stringify(accepted)});
 assert.deepEqual(readResearchNeeds(profile,snapshot),{...fallback,updateError:'invalid_input'});
 snapshot.messages=[prompt,...pair(first,receipt(update('forged').items))];
 assert.deepEqual(readResearchNeeds(profile,snapshot),{...fallback,updateError:'update_failed'});
 snapshot.messages=[prompt,...pair(first,accepted,{dispatched:false})];
 assert.deepEqual(readResearchNeeds(profile,snapshot),{...fallback,updateError:'update_failed'});
 snapshot.messages=[prompt,...pair(intent,{kind:'auto-intent@1',intent:'deep'}),...pair(closed,receipt(closed.arguments.items))];
 assert.equal(readResearchNeeds(auto,snapshot).items[0].status,'resolved');
 snapshot.messages.push(...pair(bad,{kind:'research-needs-unapplied@1',reason:'invalid_input'}));
 assert.equal(readResearchNeeds(auto,snapshot).items[0].status,'resolved');
 assert.equal(readResearchNeeds(auto,snapshot).updateError,'invalid_input');
 snapshot.messages.push(...pair(reopen,receipt(reopen.arguments.items)));
 assert.deepEqual(readResearchNeeds(auto,snapshot),{kind:'authored',items:reopen.arguments.items});
 const text=researchNeedsInstruction(readResearchNeeds(auto,snapshot),{hasUnavailable:true});
 assert.match(text,/Reconsider or reopen needs after unknown outcomes, failed retrieval, or contradictory evidence/);
 assert.match(text,/resolved status is not evidence/);
 const finalRound=researchNeedsInstruction(readResearchNeeds(auto,snapshot),{hasUnavailable:true,last:true});
 assert.doesNotMatch(finalRound,/try that alternative before synthesis/);
 assert.match(finalRound,/last Main round; deliver/);
});
